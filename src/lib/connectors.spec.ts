import { existsSync, readdirSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

import { describe, expect, it } from "vitest";

import { connectorConfigs, connectorRuntimes } from "@/lib/connectors";

// `npx rayfin connector add` and `npx rayfin connector remove` rewrite `src/lib/connectors.ts`
// only while it carries the CLI's `@generated` marker; otherwise they report manual edits and
// leave the wiring to the app.

const appRoot = process.cwd();
// The CLI writes LF; normalizing keeps a CRLF checkout from failing these tests.
const current = readFileSync(resolve(appRoot, "src/lib/connectors.ts"), "utf8").replace(/\r\n/g, "\n");

/** The scaffolded connector names. */
function scaffoldedConnectors(): string[] {
    const directory = resolve(appRoot, "rayfin/connectors");
    return existsSync(directory)
        ? readdirSync(directory, { withFileTypes: true })
            .filter((entry) => entry.isDirectory() && existsSync(resolve(directory, entry.name, "schema.ts")))
            .map((entry) => entry.name)
            .sort()
        : [];
}

describe("src/lib/connectors.ts", () => {
    it("keeps the app-owned block first and the CLI's @generated marker after it", () => {
        const end = current.indexOf("// #endregion rayfin:app-owned");
        expect(current.indexOf("// #region rayfin:app-owned")).toBe(0);
        expect(end).toBeGreaterThan(0);
        const owned = current.slice(0, end);
        expect(owned).toContain("Copyright (c) Microsoft Corporation.");
        expect(owned).toContain("export type SemanticModelConnectors");
        expect(current.slice(end)).toMatch(/^\/\/ @generated by `rayfin connector add` — do not edit below this line\.$/m);
    });

    it.skipIf(scaffoldedConnectors().length > 0)("ships empty maps until a connector is added", () => {
        expect(current).toMatch(/^export type AppConnectorsSchema = Record<string, never>;$/m);
        expect(current).toMatch(/^export const connectorConfigs: Record<string, ConnectorConfig> = \{\};$/m);
        expect(current).toMatch(/^export const connectorRuntimes: ConnectorsRuntime = \{\};$/m);
    });

    it("wires exactly the scaffolded connectors into both maps", () => {
        const scaffolded = scaffoldedConnectors();
        expect(Object.keys(connectorConfigs).sort()).toEqual(scaffolded);
        expect(Object.keys(connectorRuntimes).sort()).toEqual(scaffolded);
    });
});
